#!/usr/bin/env python
"""Stage 55 — the Lin-scheme baseline's tags as a supplementary table.

Definitions come from `docs/lin_scheme.md`, the text the annotator prompt was built from, so the
table and the prompt cannot drift apart. Prevalence and split-half reliability come from
`results/lin-features` (`gates.csv`, and `metrics.json` for `UNCODABLE`). A first-level heading
carries numbers only where that level has its own column: at least two children for that role.

    python scripts/55_lin_table.py
"""
from __future__ import annotations

import json

import _bootstrap  # noqa: F401
import pandas as pd

from ttapub import config
from ttapub.latex import caption_below
from ttapub import taxonomy_lin as L

RUN = config.RESULTS / "lin-features"


def tex(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("…", r"\dots{}"),
                 ("—", "---"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    out, open_ = [], True
    for ch in s:
        if ch == '"':
            out.append("``" if open_ else "''")
            open_ = not open_
        else:
            out.append(ch)
    return "".join(out)


def origin(source: str) -> str:
    """Prior: taken from the literature. Mixed: part prior, part ours. Ours: written for this."""
    prior = "M13" in source or "L22-P" in source
    ours = "OURS" in source
    return "Mixed" if prior and ours else ("Ours" if ours else "Prior")


def main() -> None:
    g = pd.read_csv(RUN / "gates.csv")
    assert g.passes.all(), "a failing tag may not appear in this table"
    cell = {(r.role, r.tag): rf"{r.prevalence_pct:.1f} ({r.rel_within_block10:.2f})"
            for r in g.itertuples()}

    def num(role: str, tag: str) -> str:
        return cell.get((role, tag), "---")

    tags = L.tags()
    groups: dict[str, list[str]] = {}
    for code, e in tags.items():
        if code != L.UNCODABLE:
            groups.setdefault(e["first"], []).append(code)
    head = r"tag & definition & source & tutor & student \\"
    lines = [r"% generated by scripts/55_lin_table.py from docs/lin_scheme.md and "
             r"results/lin-features -- do not edit by hand",
             r"{\footnotesize",
             r"\begin{longtable}{@{}p{0.2\linewidth}p{0.48\linewidth}lrr@{}}",
             r"\caption{\textbf{The dialogue-act scheme of the baseline.} The tags of "
             r"\citet{lin2022goodmove}, without the two image tags, with each definition as given to "
             r"the annotator. \emph{Source} shows whether a definition is taken from prior work, partly "
             r"ours, or ours. \emph{Tutor} and \emph{student} give the tag's share of that speaker's "
             r"training sentences in percent, with split-half reliability in brackets, and --- means "
             r"no column for that speaker.}\label{tab:lin}\\",
             r"\toprule", head, r"\midrule", r"\endfirsthead",
             r"\toprule", head, r"\midrule", r"\endhead",
             r"\bottomrule", r"\endfoot"]
    counts = {"Prior": 0, "Mixed": 0, "Ours": 0}
    for first, codes in groups.items():
        slug = first.lower()
        name = first.replace("_", " ").capitalize()
        # \\* keeps a group's row on the page of its first tag: never a group name alone at a break
        lines.append(rf"\emph{{{name}}} & & & {num('tutor', 'lin1_' + slug)} & "
                     rf"{num('student', 'lin1_' + slug)} \\*")
        for code in codes:
            e = tags[code]
            o = origin(e["source"])
            counts[o] += 1
            t = "lin_" + code.lower()
            lines.append(rf"\quad {tex(e['lin_name'])} & {tex(e['definition'])} & {o} & "
                         rf"{num('tutor', t)} & {num('student', t)} \\")
        lines.append(r"\addlinespace")
    assert sum(counts.values()) == 29, counts
    cov = json.loads((RUN / "metrics.json").read_text())["coverage_train"]
    e = tags[L.UNCODABLE]
    lines.append(rf"\emph{{Uncodable}} (no column) & {tex(e['definition'])} & Ours & "
                 rf"{100 * cov['tutor']['share_uncodable']:.1f} & "
                 rf"{100 * cov['student']['share_uncodable']:.1f} \\")
    lines += [r"\end{longtable}", r"}"]
    out = config.ROOT / "tables" / "table_lin.tex"
    out.write_text(caption_below("\n".join(lines) + "\n"), encoding="utf-8")
    print(f"wrote {out}; definitions by source: {counts}")


if __name__ == "__main__":
    main()
