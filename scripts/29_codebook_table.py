#!/usr/bin/env python
"""Stage 29 — the codebook as a supplementary table: every code's definition, as annotated.

The column table (stage 20) says how often each code occurs and how well it agrees; this says
what each code *means*, so a reader can interpret a column's attribution. Definitions are read
from `docs/taxonomy_v3.md` -- the text the annotator prompt was built from -- never retyped, so
the table and the prompt cannot drift apart. Codes appear in the column table's groups and order.

    python scripts/29_codebook_table.py
"""
from __future__ import annotations

import importlib.util
import pathlib

import _bootstrap  # noqa: F401

from ttapub import config
from ttapub.latex import caption_below
from ttapub import taxonomy_v3 as T

_spec = importlib.util.spec_from_file_location(
    "coltab", pathlib.Path(__file__).with_name("20_column_table.py"))
coltab = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(coltab)


def tex(s: str) -> str:
    """LaTeX-safe definition text, with straight double quotes turned into `` ''."""
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("…", r"\dots{}"),
                 ("—", "---"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    out, open_ = [], True
    for ch in s:
        if ch == '"':
            out.append("``" if open_ else "''")
            open_ = not open_
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    d = coltab.build()
    lines = [r"% generated by scripts/29_codebook_table.py from docs/taxonomy_v3.md -- do not edit by hand",
             r"{\footnotesize",
             r"\begin{longtable}{@{}p{0.27\linewidth}p{0.68\linewidth}@{}}",
             r"\caption{\textbf{The codebook.} Each code's definition as given to the annotator, "
             r"grouped as in \cref{tab:columns}. $\dagger$ marks a residual.}\label{tab:codebook}\\",
             r"\toprule", r"code & definition \\", r"\midrule", r"\endfirsthead",
             r"\toprule", r"code & definition \\", r"\midrule", r"\endhead",
             r"\bottomrule", r"\endfoot"]
    n = 0
    for role, word in (("tutor", "Tutor moves"), ("student", "Student signals")):
        pool = T.pool(role)
        for origin in coltab.ORIGIN_ORDER:
            block = d[(d.role == role) & (d.origin == origin)]
            if block.empty:
                continue
            lines.append(rf"\multicolumn{{2}}{{@{{}}l}}{{\emph{{{word} --- "
                         rf"{tex(T.ORIGIN_LABEL[origin])}}} ({len(block)})}} \\")
            for _, r in block.iterrows():
                mark = r"$^\dagger$" if r.residual else ""
                lines.append(rf"\quad {tex(r.label)}{mark} & {tex(pool[r.code]['definition'])} \\")
                n += 1
            lines.append(r"\addlinespace")
    assert n == 57, n
    lines += [r"\end{longtable}", r"}"]
    out = config.ROOT / "tables" / "table_codebook.tex"
    out.write_text(caption_below("\n".join(lines) + "\n"), encoding="utf-8")
    print(f"wrote {out} ({n} codes)")


if __name__ == "__main__":
    main()
