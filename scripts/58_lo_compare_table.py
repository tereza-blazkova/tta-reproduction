#!/usr/bin/env python
"""Stage 58 — what the code rates add to the learning objective alone, per learner.

Reads the paired differences of stage 53: `results/lo-compare` (XGBoost, logistic regression) and
`results/lo-compare-tabpfn-oof` (TabPFN, five seeds, out of fold and test), and adds the one thing neither holds: the same paired difference in log loss after
an intercept-only refit (`metrics.intercept_refit_ll`), refitted inside every bootstrap resample
on the same session clusters. A diagnostic, never a prediction: it says how much of a gain in log
loss is the level of the predictions rather than their ranking.

Every gain is signed so that positive favours the model with the code rates.

    python scripts/58_lo_compare_table.py --run lo-compare-table
"""
from __future__ import annotations

import argparse
import json

import _bootstrap  # noqa: F401
import numpy as np
import pandas as pd

from ttapub import config, data, metrics, runlog
from ttapub.latex import caption_below

#: learner -> (objective-only run, run with the code rates, stage-53 run holding the pair)
PAIRS = {"XGBoost": ("arm-lo", "arm-both", "lo-compare"),
         "Logistic regression": ("logreg-lo", "logreg-both", "lo-compare"),
         "TabPFN 3.5": ("tabpfn35-tfidf-s5-lo-oof", "tabpfn35-tfidf-s5-both-oof",
                        "lo-compare-tabpfn-oof")}
VIEWS = (("oof_all", "Out of fold"), ("test_tsl", "Held-out TSL"), ("test_eedi", "Eedi"))


def refit_gain(y, p_lo, p_both, clusters, B: int, seed: int = 0) -> dict:
    """Paired cluster bootstrap of LL*(objective only) - LL*(with the rates)."""
    rng = np.random.default_rng(seed)
    idx_by = metrics._cluster_index(clusters)
    d = []
    for _ in range(B):
        ix = np.concatenate([idx_by[g] for g in rng.integers(0, len(idx_by), len(idx_by))])
        yy = y[ix]
        if yy.min() == yy.max():
            continue
        d.append(metrics.intercept_refit_ll(yy, p_lo[ix]) - metrics.intercept_refit_ll(yy, p_both[ix]))
    return {"ll_star_lo": metrics.intercept_refit_ll(y, p_lo),
            "ll_star_both": metrics.intercept_refit_ll(y, p_both),
            "d": metrics.intercept_refit_ll(y, p_lo) - metrics.intercept_refit_ll(y, p_both),
            "ci": [float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))]}


def read_gains() -> dict:
    """{learner: {view: gains}} from the stage-53 runs, signed so positive favours the rates."""
    out: dict = {}
    for name, (lo, both, run) in PAIRS.items():
        pairs = json.loads((config.RESULTS / run / "metrics.json").read_text())["pairs"]
        out[name] = {}
        for view, _ in VIEWS:
            r = pairs[f"{lo}:{both}"][view]
            out[name][view] = {"n": r["n"], "d_ll": r["d_ll_point"], "d_ll_ci": r["d_ll_ci"],
                               "d_auroc": -r["d_auroc_point"],
                               "d_auroc_ci": [-r["d_auroc_ci"][1], -r["d_auroc_ci"][0]]}
    return out


def cell(d, ci, scale=1.0) -> str:
    return f"{d / scale:.3f} [{ci[0] / scale:.3f}, {ci[1] / scale:.3f}]".replace("-", "$-$")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="lo-compare-table")
    ap.add_argument("--boot", type=int, default=2000)
    a = ap.parse_args()
    d = runlog.start(a.run, vars(a), [])

    res = read_gains()
    test = data.load_test().reset_index(drop=True)
    sess = test.session_id.to_numpy()
    for name, (lo, both, _) in PAIRS.items():
        pl, pb = (pd.read_csv(config.RESULTS / r / "test.csv") for r in (lo, both))
        if not (pl.response_id.equals(pb.response_id) and pl.y.equals(pb.y)
                and pl.response_id.equals(test.response_id)):
            raise SystemExit(f"{name}: test rows differ")
        y = pl.y.to_numpy(float)
        for view, src in (("test_tsl", "tsl"), ("test_eedi", "eedi")):
            m = (test.data_source == src).to_numpy()
            res[name][view]["ll_star"] = refit_gain(y[m], pl.p.to_numpy()[m], pb.p.to_numpy()[m],
                                                    sess[m], a.boot)
            r = res[name][view]
            print(f"{name:20s} {view:10s} dLL {r['d_ll']:+.4f}  dLL* {r['ll_star']['d']:+.4f} "
                  f"[{r['ll_star']['ci'][0]:+.4f},{r['ll_star']['ci'][1]:+.4f}]  "
                  f"dAUROC {r['d_auroc']:+.2f}", flush=True)

    lines = [r"% generated by scripts/58_lo_compare_table.py from results/lo-compare and "
             r"results/lo-compare-tabpfn-oof -- do not edit by hand",
             r"\begin{table}[!h]", r"\centering\small",
             r"\caption{\textbf{What the code rates add to the learning objective alone.} Each row "
             r"compares a model on the code rates and the objective's text with the same model on "
             r"the text alone, on identical rows. Positive values favour the code rates. LL* refits "
             r"the intercept within each resample, so a gain in LL that disappears in LL* comes from "
             r"the level of the predictions, not their ranking. Brackets are 95\% paired bootstrap "
             r"intervals, resampling objectives out of fold and sessions on test, without run-to-run "
             r"randomness.}",
             r"\label{tab:lo-compare}",
             r"\begin{tabular}{@{}llccc@{}}", r"\toprule",
             r"View & Model & Lower LL & Lower LL* & Higher AUROC \\", r"\midrule"]
    for i, (view, label) in enumerate(VIEWS):
        rows = [k for k in PAIRS if view in res[k]]
        if i:
            lines.append(r"\midrule")
        for j, name in enumerate(rows):
            r = res[name][view]
            star = cell(r["ll_star"]["d"], r["ll_star"]["ci"]) if "ll_star" in r else "---"
            lines.append(f"{label if j == 0 else ''} & {name} & {cell(r['d_ll'], r['d_ll_ci'])} & "
                         f"{star} & {cell(r['d_auroc'], r['d_auroc_ci'], 100)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    out = config.ROOT / "tables" / "table_lo_compare.tex"
    out.write_text(caption_below("\n".join(lines)))
    print(f"wrote {out}", flush=True)
    runlog.finish(d, {"run": a.run, "gains": res})


if __name__ == "__main__":
    main()
